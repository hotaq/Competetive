"""Turn submission/ into a CPU Kaggle notebook that writes /kaggle/working/submission.zip.

The bundle is checked with the scorer's own code (adk_submission + swegemma) first,
so a broken config fails here instead of burning the one submission per day.

    .venv/bin/python scripts/build_kernel.py [--slug gemma4-agent-baseline]
    kaggle kernels push -p kernel
"""

import argparse
import json
import tempfile
import zipfile
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
USER = "chinnaphatkhun"

CELL = '''import zipfile
from pathlib import Path

FILES = {files}

out = Path("/kaggle/working")
for rel, text in FILES.items():  # unzipped copy + zip, same layout as the 0.12 notebook's output
    p = out / "submission" / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
with zipfile.ZipFile(out / "submission.zip", "w", zipfile.ZIP_DEFLATED) as z:
    for rel, text in sorted(FILES.items()):
        z.writestr(rel, text)
print(*sorted(FILES), sep="\\n")
'''


def validate(sub: Path) -> None:
    """Same checks the scorer runs before starting vLLM (agent_runner.py, models/discovery.py)."""
    from adk_submission import compile_submission, validate_directory
    from swegemma.config import build_submission_limits
    from swegemma.models import validate_single_declared_model
    from swegemma.models.registry import setup_gemma_model_registry
    from swegemma.tools import create_tools

    limits, gen = build_submission_limits()
    validate_directory(sub, limits=limits)
    model = validate_single_declared_model(sub)
    agent = compile_submission(
        sub,
        tool_registry=create_tools(SimpleNamespace()),  # tools are only bound, never called
        model_registry=setup_gemma_model_registry(),
        limits=limits,
        generation_constraints=gen,
    )
    print(f"compiled OK: root={agent.name} model={model}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", default="gemma4-agent-baseline")
    ap.add_argument("--src", default=str(ROOT / "submission"))
    ap.add_argument("--out", default=str(ROOT / "kernel"))
    args = ap.parse_args()

    src = Path(args.src)
    paths = [p for p in sorted(src.rglob("*"))
             if p.is_file() and not p.name.startswith(".") and "__pycache__" not in p.parts]
    if any(p.suffix == ".safetensors" for p in paths):
        # ponytail: text-only inlining; ship adapters as a Kaggle dataset when LoRA work starts
        raise SystemExit("adapters can't be inlined into the notebook yet")
    files = {p.relative_to(src).as_posix(): p.read_text() for p in paths}
    cell = CELL.format(files=json.dumps(files, indent=1))

    # Run the generated cell against a temp dir: validate exactly what the scorer will unpack.
    with tempfile.TemporaryDirectory() as tmp:
        exec(cell.replace("/kaggle/working", tmp), {})
        with zipfile.ZipFile(f"{tmp}/submission.zip") as z:
            assert {n: z.read(n).decode() for n in z.namelist()} == files
        validate(Path(tmp) / "submission")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    nb = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"}},
        "cells": [
            {"cell_type": "markdown", "metadata": {}, "source": "Generated by `scripts/build_kernel.py` from `submission/`. Edit there, not here."},
            {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": cell},
        ],
    }
    (out / f"{args.slug}.ipynb").write_text(json.dumps(nb, indent=1))
    meta = {
        "id": f"{USER}/{args.slug}",
        "title": args.slug,
        "code_file": f"{args.slug}.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": False,  # scoring runs on the host's 4x L4; a CPU notebook scores fine
        "enable_internet": False,
        "competition_sources": ["gemma-4-developer-agent"],
        "dataset_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {out}/{args.slug}.ipynb ({len(files)} files)")


if __name__ == "__main__":
    main()
