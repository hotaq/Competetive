"""Build the standalone shop_router_v1 submission bundle.

Inlines the policy module and the vendored route data into one self-contained main.py that
imports only the standard library, then proves the bundle plays the same actions as
`ShopRouterV1.from_file()` on a few seeds before writing submission.tar.gz and candidate.json.
Never hand-edit the output; change the policy or the route data and rebuild.
"""

from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import io
import json
import runpy
import tarfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POLICY_PATH = ROOT / "src" / "kaggriculture_rl" / "policy" / "shop_router_v1.py"
ROUTES_PATH = ROOT / "artifacts" / "shop_router_v1" / "yusuke_routes.json"
DEFAULT_OUTPUT_DIR = ROOT / "submissions" / "shop_router_v1_standalone"
BUNDLE_NAME = "shop_router_v1_standalone"
EMBEDDED_MODULE = "shop_router_v1_bundle_policy"
MAX_SHOPS = 2
EQUIVALENCE_STEPS = 160  # past both branch steps (72, 144)

LOADER_SOURCE = '''
def _load_embedded_module(name, source):
    module = types.ModuleType(name)
    module.__file__ = "<embedded-module:" + name + ">"
    sys.modules[name] = module
    exec(compile(source, module.__file__, "exec"), module.__dict__)
    return module
'''


def build_main(routes_path: Path = ROUTES_PATH) -> str:
    policy_source = POLICY_PATH.read_text(encoding="utf-8")
    routes = json.loads(routes_path.read_text(encoding="utf-8"))
    payload = {key: routes[key] for key in ("first_branch_step", "second_branch_step",
                                            "first_routes", "second_routes", "routes")}
    blob = base64.b85encode(
        zlib.compress(json.dumps(payload, separators=(",", ":"), sort_keys=True).encode("utf-8"), 9)
    ).decode("ascii")
    lines = [
        '"""Standalone shop_router_v1 bundle.',
        "Generated by scripts/build_shop_router_v1_submission.py.",
        "",
        "Two-shop tape router (Yusuke Hayashi's published method, routes vendored under",
        "artifacts/shop_router_v1/). Do not hand-edit; rebuild from the source policy.",
        '"""',
        "from __future__ import annotations",
        "",
        "import base64",
        "import json",
        "import sys",
        "import types",
        "import zlib",
        "",
        LOADER_SOURCE.strip("\n"),
        "",
        "_POLICY_SOURCE = " + repr(policy_source),
        "_ROUTES_BLOB = " + repr(blob),
        "",
        "_policy = _load_embedded_module(" + repr(EMBEDDED_MODULE) + ", _POLICY_SOURCE)",
        "_ROUTER = _policy.ShopRouterV1(",
        '    json.loads(zlib.decompress(base64.b85decode(_ROUTES_BLOB)).decode("utf-8")),',
        f"    max_shops={MAX_SHOPS},",
        ")",
        "",
        "",
        "def agent(observation, configuration=None):",
        "    return _ROUTER.agent(observation, configuration)",
        "",
    ]
    return "\n".join(lines)


def write_tarball(output_dir: Path, main_bytes: bytes) -> Path:
    tar_buffer = io.BytesIO()
    with tarfile.open(fileobj=tar_buffer, mode="w") as archive:
        info = tarfile.TarInfo("main.py")
        info.size = len(main_bytes)
        info.mode = 0o644
        info.mtime = 0
        info.uid = info.gid = 0
        info.uname = info.gname = ""
        archive.addfile(info, io.BytesIO(main_bytes))
    raw = io.BytesIO()
    with gzip.GzipFile(filename="", mtime=0, compresslevel=9, fileobj=raw, mode="wb") as zipped:
        zipped.write(tar_buffer.getvalue())
    path = output_dir / "submission.tar.gz"
    path.write_bytes(raw.getvalue())
    return path


def verify_equivalence(
    main_path: Path, seeds: tuple[int, ...], routes_path: Path = ROUTES_PATH,
) -> int:
    from kaggriculture_rs import Engine

    from kaggriculture_rl.policy.shop_router_v1 import ShopRouterV1

    bundled = runpy.run_path(str(main_path))["agent"]
    reference = ShopRouterV1.from_file(routes_path, max_shops=MAX_SHOPS)
    checked = 0
    for seed in seeds:
        engine = Engine({"episodeSteps": 720, "seed": seed, "weedSpawnChance": 0.005})
        for _step in range(EQUIVALENCE_STEPS):
            for seat in (0, 1):
                observation = engine.observation(seat)
                if bundled(observation, None) != reference.agent(observation, None):
                    raise RuntimeError(f"divergence at seed {seed} step {_step} seat {seat}")
                checked += 1
            left = reference.agent(engine.observation(0), None)
            right = reference.agent(engine.observation(1), None)
            engine.step([left, right])
    return checked


def build(
    output_dir: Path,
    seeds: tuple[int, ...] = (208248505, 1219301430, 15100001),
    routes_path: Path = ROUTES_PATH,
    name: str = BUNDLE_NAME,
    evidence: str = "analysis/v96_shop_router_20260905/",
) -> dict:
    output_dir = Path(output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    main_text = build_main(routes_path)
    main_bytes = main_text.encode("utf-8")
    main_path = output_dir / "main.py"
    main_path.write_text(main_text, encoding="utf-8")
    checked = verify_equivalence(main_path, seeds, routes_path)
    tarball = write_tarball(output_dir, main_bytes)
    routes = json.loads(routes_path.read_text(encoding="utf-8"))

    def rel(path: Path) -> str:
        return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)

    metadata = {
        "name": name,
        "agent_file": rel(main_path),
        "archive": rel(tarball),
        "archive_bytes": len(tarball.read_bytes()),
        "archive_sha256": hashlib.sha256(tarball.read_bytes()).hexdigest(),
        "main_bytes": len(main_bytes),
        "main_sha256": hashlib.sha256(main_bytes).hexdigest(),
        "policy_sha256": hashlib.sha256(POLICY_PATH.read_bytes()).hexdigest(),
        "routes_file": rel(routes_path),
        "routes_sha256": hashlib.sha256(routes_path.read_bytes()).hexdigest(),
        "route_sha256": routes.get("route_sha256"),
        "route_names": routes.get("route_names"),
        "max_shops": MAX_SHOPS,
        "equivalence_checks": checked,
        "equivalence_seeds": list(seeds),
        "evidence": evidence,
        "status": "standalone_validated",
    }
    payload = json.dumps(metadata, indent=2) + "\n"
    (output_dir / "candidate.json").write_text(payload, encoding="utf-8")
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--routes", type=Path, default=ROUTES_PATH)
    parser.add_argument("--name", default=BUNDLE_NAME)
    parser.add_argument("--evidence", default="analysis/v96_shop_router_20260905/")
    args = parser.parse_args()
    metadata = build(
        args.output_dir, routes_path=args.routes, name=args.name, evidence=args.evidence,
    )
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
