import pandas as pd, numpy as np
tr = pd.read_csv('train.csv')
te = pd.read_csv('test.csv')
print(f'TRAIN {tr.shape} TEST {te.shape}')
print('--- dtypes ---')
print(tr.dtypes.to_string())
print('duplicates train:', tr.duplicated().sum(), ' test:', te.duplicated().sum())
print('id unique train:', tr.id.nunique(), ' test:', te.id.nunique(), ' overlap:', len(set(tr.id) & set(te.id)))
print('--- target ---')
print(tr.Will_Buy_EV.value_counts())
print(tr.Will_Buy_EV.value_counts(normalize=True).round(4))
num = ['Age','Annual_Income_USD','Daily_Commute_km','Number_of_Cars_Owned','Charging_Stations_Near_Home','Charging_Stations_Near_Work','Environmental_Concern_Level']
print('--- numeric describe ---')
print(tr[num].describe().round(2).to_string())
print('--- categorical levels ---')
for c in ['Gender','City_Type','Current_Car_Type','Home_Charging_Possible','Subsidy_Available','Range_Anxiety_Level']:
    print(c, dict(tr[c].value_counts().to_dict()))
print('--- TARGET RATE by categorical ---')
for c in ['Gender','City_Type','Current_Car_Type','Home_Charging_Possible','Subsidy_Available','Range_Anxiety_Level','Environmental_Concern_Level','Number_of_Cars_Owned']:
    t = tr.groupby(c, observed=True)['Will_Buy_EV'].apply(lambda s: (s=='Yes').mean()).sort_values(ascending=False)
    print(c)
    print((t*100).round(2).to_string() + ' %Yes')
print('--- numeric mean by target ---')
print(tr.groupby('Will_Buy_EV')[num].mean().round(2).to_string())
print('--- train vs test shift ---')
cmp = pd.DataFrame({'train_mean': tr[num].mean(), 'test_mean': te[num].mean()})
cmp['diff_pct'] = ((cmp.test_mean-cmp.train_mean)/cmp.train_mean*100).round(2)
print(cmp.round(2).to_string())
for c in ['Gender','City_Type','Current_Car_Type','Home_Charging_Possible','Subsidy_Available','Range_Anxiety_Level']:
    a = tr[c].value_counts(normalize=True).sort_index()
    b = te[c].value_counts(normalize=True).sort_index()
    d = (b-a).abs().sort_values(ascending=False)
    print(c, 'max shift:', d.index[0], f'{d.iloc[0]*100:.2f}pp')
print('--- corr with target ---')
y = (tr.Will_Buy_EV=='Yes').astype(int)
corr = tr[num].apply(lambda s: s.corr(y)).sort_values(ascending=False)
print(corr.round(3).to_string())
print('--- numeric inter-corr ---')
print(tr[num].corr().round(2).to_string())
