#!/usr/bin/env python3
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPLAY_DIR = ROOT / ".omx/research/sim/gui/replays"
SIM_DIR = ROOT / ".omx/research/sim"
OUT = ROOT / "docs/RUNS_INDEX.md"


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def load_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text())
    except Exception:
        return {}


def replay_rows() -> list[str]:
    rows: list[tuple[float, str]] = []
    for path in sorted(REPLAY_DIR.glob("*.json")):
        if path.name.endswith(".summary.json"):
            continue
        data = load_json(path)
        games = data.get("games") or []
        summaries = data.get("summaries") or []
        seeds = data.get("seeds") or [game.get("seed") for game in games if game.get("seed") is not None]
        agents = data.get("agents") or []
        latest_wins = sum(1 for game in games if 0 in game.get("winners", []))
        old_wins = sum(1 for game in games if 1 in game.get("winners", []))
        totals = [game.get("totals") for game in games if game.get("totals")]
        summary_path = path.with_suffix(".summary.json")
        report_path = path.with_suffix(".report.md")
        events_path = path.with_suffix(".events.csv")
        insight_path = path.with_suffix(".insights.md")
        links = [f"[json]({rel(path)})"]
        if report_path.exists():
            links.append(f"[report]({rel(report_path)})")
        if events_path.exists():
            links.append(f"[events]({rel(events_path)})")
        if summary_path.exists():
            links.append(f"[summary]({rel(summary_path)})")
        if insight_path.exists():
            links.append(f"[insights]({rel(insight_path)})")
        label = data.get("label") or path.stem
        mtime = path.stat().st_mtime
        rows.append((
            mtime,
            "| {name} | {label} | `{agents}` | `{seeds}` | {lw}-{ow} | `{totals}` | {links} |".format(
                name=path.stem,
                label=label,
                agents=", ".join(agents),
                seeds=seeds,
                lw=latest_wins,
                ow=old_wins,
                totals=totals,
                links=" ".join(links),
            ),
        ))
    return [row for _, row in sorted(rows, reverse=True)]


def compare_rows() -> list[str]:
    rows: list[tuple[float, str]] = []
    report_paths = set(SIM_DIR.rglob("*compare*.md"))
    report_paths.update(SIM_DIR.rglob("*ffa4*.md"))
    for path in sorted(report_paths):
        if "gui/" in path.as_posix():
            continue
        title = path.stem
        kind = "ffa4" if "ffa4" in title else ("full" if "full" in title else ("quick" if "quick" in title else "mixed"))
        csv_path = path.with_suffix(".csv")
        jsonl_path = path.with_suffix(".jsonl")
        links = [f"[md]({rel(path)})"]
        if csv_path.exists():
            links.append(f"[csv]({rel(csv_path)})")
        if jsonl_path.exists():
            links.append(f"[jsonl]({rel(jsonl_path)})")
        rows.append((path.stat().st_mtime, f"| {title} | {kind} | {' '.join(links)} |"))
    return [row for _, row in sorted(rows, reverse=True)]


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = [
        "# Orbit Wars run index",
        "",
        "Generated by `scripts/index_runs.py`.",
        "",
        "## Replay GUI runs",
        "",
        "| run | label | agents | seeds | latest-old wins | totals | files |",
        "|---|---|---|---|---:|---|---|",
        *replay_rows(),
        "",
        "## Compare reports",
        "",
        "| report | kind | files |",
        "|---|---|---|",
        *compare_rows(),
        "",
    ]
    OUT.write_text("\n".join(text))
    print(f"WROTE {rel(OUT)}")


if __name__ == "__main__":
    main()
